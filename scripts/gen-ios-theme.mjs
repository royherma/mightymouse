#!/usr/bin/env node
// Generate ios/MightyMouse/Generated/Theme.swift from CONFIG.THEME_TOKENS.
//
// Swift is the one surface that can't consume the shared tokens the way every
// other one does: src/renderer/src/theme.ts injects them as CSS custom
// properties at runtime (8 lines -- a loop, a camel->kebab regex,
// setProperty), and src/main/phone-remote/react/main.tsx mirrors that exactly.
// A WKWebView inherits it for free. SwiftUI can't read a CSS var, so the
// native chrome has to be handed real Swift values -- and the only safe way to
// do that is to generate them, because theme.css's header documents
// hand-copied colors as the precise bug that port was written to end.
//
// Same text-slicing approach as scripts/release-body.mjs: config.ts is
// TypeScript and plain node can't import it, so slice the one block we need.
// A parse failure is a hard exit, never a silent fallback -- a mis-parsed color
// renders black, which looks like a design choice rather than a broken build.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'

const CONFIG_PATH = new URL('../src/shared/config/theme-tokens.ts', import.meta.url)
const OUT_PATH = new URL('../ios/MightyMouse/Generated/Theme.swift', import.meta.url)
const WEB_CSS = ['web/v2.css', 'web/style-v1.css'].map((p) => new URL(`../${p}`, import.meta.url))
const WEB_START = '/* THEME_TOKENS start - generated by scripts/gen-ios-theme.mjs, do not edit */'
const WEB_END = '/* THEME_TOKENS end */'

/** Slice the THEME_TOKENS object literal out of config/theme-tokens.ts. */
export function extractTokenBlock(source) {
  const start = source.indexOf('THEME_TOKENS = {')
  if (start === -1) throw new Error('THEME_TOKENS not found in config/theme-tokens.ts')
  // Brace-match rather than regex to the closing brace: the block contains
  // comments with apostrophes and nested parens, and a greedy match would run
  // past the end of the object.
  let depth = 0
  for (let i = source.indexOf('{', start); i < source.length; i++) {
    if (source[i] === '{') depth++
    else if (source[i] === '}') {
      depth--
      if (depth === 0) return source.slice(start, i + 1)
    }
  }
  throw new Error('THEME_TOKENS block is unterminated')
}

/** key -> value for every `name: 'value'` pair, comments stripped. */
export function parseTokens(block) {
  const withoutComments = block
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/[^\n]*/g, '')
  const tokens = {}
  for (const [, key, val] of withoutComments.matchAll(/([A-Za-z][A-Za-z0-9]*)\s*:\s*'([^']*)'/g)) {
    tokens[key] = val
  }
  if (Object.keys(tokens).length === 0) throw new Error('no tokens parsed from THEME_TOKENS')
  return tokens
}

// 'rgba(255,160,80,0.96)' -> {r,g,b,a} normalised 0-1. Null for a non-rgba()
// literal, so callers can route it to a non-color emitter.
export function parseRgba(value) {
  const m = /^rgba\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\)$/.exec(value.trim())
  if (!m) return null
  const [r, g, b, a] = m.slice(1).map(Number)
  if ([r, g, b].some((c) => c < 0 || c > 255) || a < 0 || a > 1) {
    throw new Error(`rgba component out of range: ${value}`)
  }
  return { r: r / 255, g: g / 255, b: b / 255, a }
}

/** '14px' -> 14. Returns null if not a px literal. */
export function parsePx(value) {
  const m = /^(-?[\d.]+)px$/.exec(value.trim())
  return m ? Number(m[1]) : null
}

/** '255, 160, 80' -> [255,160,80]. Returns null if not a bare triplet. */
export function parseTriplet(value) {
  const m = /^\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*$/.exec(value)
  return m ? m.slice(1).map(Number) : null
}

const f = (n) => (Number.isInteger(n) ? `${n}.0` : String(Number(n.toFixed(6))))

// Routes by VALUE SHAPE, not name: a name list would silently misroute the
// 74th key.
export function classify(tokens) {
  const colors = {}
  const spacing = {}
  const radius = {}
  const fonts = {}
  const triplets = {}
  const shadows = {}

  for (const [key, value] of Object.entries(tokens)) {
    const rgba = parseRgba(value)
    if (rgba) {
      colors[key] = rgba
      continue
    }
    const px = parsePx(value)
    if (px !== null) {
      if (key.startsWith('space')) spacing[key] = px
      else if (key.startsWith('radius')) radius[key] = px
      else if (key.startsWith('font')) fonts[key] = px
      else spacing[key] = px
      continue
    }
    const triplet = parseTriplet(value)
    if (triplet) {
      triplets[key] = triplet
      continue
    }
    // Multi-layer CSS shadows have no SwiftUI equivalent, so emit the raw
    // string as a comment for the primitive author instead of dropping it.
    shadows[key] = value
  }
  return { colors, spacing, radius, fonts, triplets, shadows }
}

const stripPrefix = (key, prefix) => {
  const bare = key.slice(prefix.length)
  return bare.charAt(0).toLowerCase() + bare.slice(1)
}

// space1..space6 strip to "1".."6" — `static let 1: CGFloat` doesn't compile,
// so spell the digit: MMSpace.four.
const SPACE_WORDS = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight']

const spaceName = (key) => {
  const bare = stripPrefix(key, 'space')
  if (/^\d+$/.test(bare)) {
    const word = SPACE_WORDS[Number(bare)]
    if (!word) throw new Error(`no Swift name for spacing step ${key}`)
    return word
  }
  return bare
}

export function emitSwift(tokens) {
  const { colors, spacing, radius, fonts, triplets, shadows } = classify(tokens)
  const L = []

  L.push('// Generated by scripts/gen-ios-theme.mjs from CONFIG.THEME_TOKENS.')
  L.push('// DO NOT EDIT. Run `npm run gen:ios-theme` after changing src/shared/config/theme-tokens.ts.')
  L.push('//')
  L.push('// Every color, radius, spacing step and font size the native iOS chrome is')
  L.push('// allowed to use lives here. A literal in a hand-written Swift file is a bug:')
  L.push('// if a value is not in THEME_TOKENS it is not a MightyMouse value.')
  L.push('')
  L.push('import SwiftUI')
  L.push('')

  L.push('enum MMColor {')
  for (const [key, { r, g, b, a }] of Object.entries(colors)) {
    L.push(`    static let ${key} = Color(.sRGB, red: ${f(r)}, green: ${f(g)}, blue: ${f(b)}, opacity: ${f(a)})`)
  }
  L.push('}')
  L.push('')

  L.push('enum MMSpace {')
  for (const [key, px] of Object.entries(spacing)) {
    L.push(`    static let ${key.startsWith('space') ? spaceName(key) : key}: CGFloat = ${f(px)}`)
  }
  L.push('}')
  L.push('')

  L.push('enum MMRadius {')
  for (const [key, px] of Object.entries(radius)) {
    L.push(`    static let ${stripPrefix(key, 'radius')}: CGFloat = ${f(px)}`)
  }
  L.push('}')
  L.push('')

  L.push('enum MMFont {')
  for (const [key, px] of Object.entries(fonts)) {
    L.push(`    static let ${stripPrefix(key, 'font')}: CGFloat = ${f(px)}`)
  }
  L.push('}')
  L.push('')

  L.push('// RGB triplets — the CSS side passes these to rgba() at use time. Kept as')
  L.push('// Color values so Swift consumers never re-assemble them by hand.')
  L.push('enum MMRgb {')
  for (const [key, [r, g, b]] of Object.entries(triplets)) {
    const name = key.endsWith('Rgb') ? key.slice(0, -3) : key
    L.push(`    static let ${name} = Color(.sRGB, red: ${f(r / 255)}, green: ${f(g / 255)}, blue: ${f(b / 255)}, opacity: 1.0)`)
  }
  L.push('}')
  L.push('')

  // The CSS shadow strings are deliberately NOT emitted: SwiftUI has no
  // multi-layer box-shadow, so MMShadow in Primitives.swift approximates them
  // and no Swift consumer can use the raw values. Read them in THEME_TOKENS.
  void shadows

  return L.join('\n')
}

export function emitCssBlock(tokens) {
  const vars = Object.entries(tokens).map(([k, v]) => `  --${k.replace(/([A-Z])/g, '-$1').toLowerCase()}: ${v};`)
  return [WEB_START, ':root {', ...vars, '}', WEB_END].join('\n')
}

export function spliceCssBlock(css, block) {
  const a = css.indexOf(WEB_START)
  const b = css.indexOf(WEB_END)
  if (a === -1 || b === -1) throw new Error(`theme block markers missing - add ${WEB_START} ... ${WEB_END} at the top`)
  return css.slice(0, a) + block + css.slice(b + WEB_END.length)
}

function main() {
  const source = readFileSync(CONFIG_PATH, 'utf8')
  const tokens = parseTokens(extractTokenBlock(source))
  const swift = emitSwift(tokens)

  const outPath = new URL(OUT_PATH)
  mkdirSync(dirname(outPath.pathname), { recursive: true })

  if (process.argv.includes('--check')) {
    let existing = null
    try {
      existing = readFileSync(outPath, 'utf8')
    } catch {
      console.error('Theme.swift missing — run `npm run gen:ios-theme`')
      process.exit(1)
    }
    if (existing !== swift) {
      console.error(
        'Theme.swift is stale: src/shared/config/theme-tokens.ts changed without regenerating.\n' +
          'Run `npm run gen:ios-theme` and commit the result.'
      )
      process.exit(1)
    }
    for (const url of WEB_CSS) {
      const css = readFileSync(url, 'utf8')
      if (spliceCssBlock(css, emitCssBlock(tokens)) !== css) {
        console.error(`${url.pathname} theme block is stale - run \`npm run gen:ios-theme\``)
        process.exit(1)
      }
    }
    console.log(`ios + web theme in sync (${Object.keys(tokens).length} tokens)`)
    return
  }

  for (const url of WEB_CSS) writeFileSync(url, spliceCssBlock(readFileSync(url, 'utf8'), emitCssBlock(tokens)))
  writeFileSync(outPath, swift)
  console.log(`wrote ${Object.keys(tokens).length} tokens -> ios/MightyMouse/Generated/Theme.swift`)
}

const isMain = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href
if (isMain) main()
